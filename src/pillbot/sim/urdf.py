"""Export the arm as a URDF (for ROS 2: RViz, MoveIt, Gazebo) from the same config as the MuJoCo sim.

  python -m pillbot.sim.urdf                     writes hardware/urdf/pillbot.urdf
  python -m pillbot.sim.urdf --check             ... and checks it against the MuJoCo model

Same joints, names and limits as the sim (and as LeRobot: shoulder_pan, shoulder_lift, elbow_flex,
wrist_roll, gripper). Meshes are your STLs (hardware/stl, scaled mm -> m), referenced relative to the
URDF file. For a ROS package, copy hardware/stl into the package and switch the paths to
package://<your_pkg>/... (docs/simulation.md, "ROS").
"""
import argparse
import math
from pathlib import Path

import numpy as np

from pillbot.sim.scene import FIXED_FACE, JAW_HINGE, grasp_point
from pillbot.utils.config import ROOT, get_bottle, load_yaml

OUT = ROOT / "hardware/urdf/pillbot.urdf"
MESH = "../stl"            # hardware/urdf -> hardware/stl


def _inertial(mass, xyz=(0, 0, 0), i=1e-5) -> str:
    return (f'<inertial><origin xyz="{xyz[0]} {xyz[1]} {xyz[2]}"/><mass value="{mass}"/>'
            f'<inertia ixx="{i}" ixy="0" ixz="0" iyy="{i}" iyz="0" izz="{i}"/></inertial>')


def _mesh(file, xyz_mm=(0, 0, 0), rpy=(0, 0, 0), rgba="0.95 0.55 0.15 1") -> str:
    x, y, z = (v / 1000 for v in xyz_mm)
    return (f'<visual><origin xyz="{x} {y} {z}" rpy="{rpy[0]} {rpy[1]} {rpy[2]}"/>'
            f'<geometry><mesh filename="{MESH}/{file}" scale="0.001 0.001 0.001"/></geometry>'
            f'<material name="m_{Path(file).stem}"><color rgba="{rgba}"/></material></visual>')


def _joint(name, parent, child, xyz, axis, lim_deg, effort=0.52) -> str:
    lo, hi = (math.radians(v) for v in lim_deg)
    return (f'<joint name="{name}" type="revolute"><parent link="{parent}"/><child link="{child}"/>'
            f'<origin xyz="{xyz[0]} {xyz[1]} {xyz[2]}" rpy="0 0 0"/><axis xyz="{axis}"/>'
            f'<limit lower="{lo:.4f}" upper="{hi:.4f}" effort="{effort}" velocity="5"/></joint>')


def build_urdf(sim: dict, bottle: dict) -> str:
    a = sim["arm"]
    lim = a["limits_deg"]
    L1, L2, h0 = a["upper_arm"], a["forearm"], a["shoulder_height"]
    g = grasp_point({**a, "cap_height": sim["fixture"]["cap_height"]}, bottle["cap_diameter_mm"] / 2000)
    tq = a["torque"]
    grey = "0.7 0.7 0.75 1"
    white = "0.9 0.9 0.92 1"
    return f"""<?xml version="1.0"?>
<!-- Generated by `python -m pillbot.sim.urdf` from configs/sim.yaml — edit that, not this file. -->
<robot name="pillbot">
  <mujoco><compiler strippath="false" balanceinertia="true" discardvisual="false" fusestatic="false"/></mujoco>
  <link name="base_link">{_inertial(0.5)}
    {_mesh("arm/base.stl", (0.8, -5.9, 38.4 + a['base_riser'] * 1000), rgba="0.6 0.6 0.65 1")}
    {_mesh("arm/base_plate.stl", (0.8, -5.9, 38.4 + a['base_riser'] * 1000), rgba="0.4 0.4 0.45 1")}
  </link>
  {_joint("shoulder_pan", "base_link", "pan_link", (0, 0, a['base_riser']), "0 0 1", lim['shoulder_pan'], tq['shoulder_pan'])}
  <link name="pan_link">{_inertial(0.15, (0, 0, h0 / 2))}
    <visual><origin xyz="0 0 {h0 / 2}"/><geometry><cylinder radius="0.03" length="{h0}"/></geometry>
      <material name="tower"><color rgba="0.6 0.6 0.65 1"/></material></visual>
  </link>
  {_joint("shoulder_lift", "pan_link", "upper_arm", (0, 0, h0), "0 1 0", lim['shoulder_lift'], tq['shoulder_lift'])}
  <link name="upper_arm">{_inertial(a['link_mass'], (0, 0, L1 / 2), 1e-4)}
    {_mesh("arm/link_1.stl", (0.8, -6.05, -166.3))}
    {_mesh("arm/elbow_1.stl", (0.8, -6.05, -166.3), rgba=grey)}
    {_mesh("arm/elbow_2.stl", (0.8, -6.05, -166.3), rgba=grey)}
  </link>
  {_joint("elbow_flex", "upper_arm", "forearm", (0, 0, L1), "0 1 0", lim['elbow_flex'], tq['elbow_flex'])}
  <link name="forearm">{_inertial(a['link_mass'], (0, 0, L2 / 2), 1e-4)}
    {_mesh("arm/link_2.stl", (0.75, 1.99, -345.6))}
    {_mesh("arm/wrist_gear_1.stl", (0.75, 1.99, -345.6), rgba=grey)}
  </link>
  {_joint("wrist_roll", "forearm", "gripper_link", (0, 0, L2), "0 0 1", lim['wrist_roll'], tq['wrist_roll'])}
  <link name="gripper_link">{_inertial(0.08, (-0.01, 0.01, 0.05))}
    {_mesh("gripper_so101/wrist_roll_follower_so101.stl", rgba=white)}
  </link>
  {_joint("gripper", "gripper_link", "moving_jaw", JAW_HINGE, "0 1 0", a['jaw_range_deg'])}
  <link name="moving_jaw">{_inertial(0.03, (-0.008, 0.019, 0.04))}
    {_mesh("gripper_so101/moving_jaw_so101.stl", (0, 18.9, 0), rpy=(-math.pi / 2, 0, 0), rgba=white)}
  </link>
  <!-- where the cap's centre sits when gripped against the fixed jaw ({bottle['name']}) -->
  <joint name="grasp_joint" type="fixed"><parent link="gripper_link"/><child link="grasp_frame"/>
    <origin xyz="{g[0]:.4f} {g[1]} {g[2]}" rpy="0 0 0"/></joint>
  <link name="grasp_frame"/>
  <!-- fixed jaw inner face, for reference: {FIXED_FACE} (x, z in m, gripper_link frame) -->
</robot>
"""


def check(path: Path, sim: dict, bottle: dict, n: int = 50) -> float:
    """Load the URDF in MuJoCo and compare the grasp frame with SimWorld's for random joint angles."""
    import mujoco
    from pillbot.sim.world import SimWorld
    m = mujoco.MjModel.from_xml_path(str(path))
    d = mujoco.MjData(m)
    w = SimWorld(bottle, sim_cfg=sim)
    rng = np.random.default_rng(0)
    worst = 0.0
    names = ("shoulder_pan", "shoulder_lift", "elbow_flex", "wrist_roll")
    gb = m.body("grasp_frame").id
    for _ in range(n):
        q = {j: rng.uniform(*sim["arm"]["limits_deg"][j]) * 0.8 for j in names}
        for j, v in q.items():
            d.qpos[m.jnt_qposadr[m.joint(j).id]] = math.radians(v)
        mujoco.mj_kinematics(m, d)
        p_sim, _ = w.fk(q)
        worst = max(worst, float(np.linalg.norm(d.xpos[gb] - p_sim)))
    return worst


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--bottle", default="standard_amber_40dr")
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    sim, bottle = load_yaml("configs/sim.yaml"), get_bottle(args.bottle)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(build_urdf(sim, bottle))
    print(f"wrote {args.out}")
    if args.check:
        err = check(args.out, sim, bottle)
        print(f"grasp frame vs MuJoCo sim over 50 random poses: worst difference {err * 1000:.3f} mm")


if __name__ == "__main__":
    main()
